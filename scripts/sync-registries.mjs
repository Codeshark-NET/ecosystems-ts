#!/usr/bin/env node
// Regenerates src/generated/registries.ts from `GET /registries`.
//
// Emits facts only: the default registry per purl_type, and the purl_types that have no
// default. The judgement calls (aliases, pins, types with no registry) live in
// src/purl.ts, guarded by the "generated snapshot" tests.
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "src", "generated", "registries.ts");

const REGISTRIES_URL = "https://packages.ecosyste.ms/api/v1/registries";
const USER_AGENT =
  "ecosystems-ts sync-registries (https://github.com/ecosyste-ms/ecosystems-ts)";

/**
 * Fetches every page.
 *
 * `/registries` caps per_page at 100 and serves 109 registries, so an unpaginated request
 * silently drops 9 of them and one whole purl_type.
 */
async function fetchRegistries() {
  const all = [];
  let url = `${REGISTRIES_URL}?per_page=100`;

  while (url) {
    const response = await fetch(url, { headers: { "User-Agent": USER_AGENT } });
    if (!response.ok) throw new Error(`GET ${url} failed with status ${response.status}`);

    const page = await response.json();
    if (!Array.isArray(page)) throw new Error(`GET ${url} did not return an array`);
    all.push(...page);

    url = nextLink(response.headers.get("link"));
  }

  if (all.length === 0) throw new Error("no registries returned");
  return all;
}

/** Minimal RFC 8288 `rel="next"` reader. */
function nextLink(header) {
  if (!header) return null;
  for (const part of header.split(",")) {
    const match = /^\s*<([^>]+)>\s*;\s*rel\s*=\s*"?next"?/i.exec(part);
    if (match) return match[1];
  }
  return null;
}

function groupByPurlType(registries) {
  /** @type {Map<string, {default: string | null, names: string[]}>} */
  const byType = new Map();

  for (const registry of registries) {
    const { purl_type: type, name, default: isDefault } = registry;
    if (typeof type !== "string" || type === "" || typeof name !== "string") continue;

    const entry = byType.get(type) ?? { default: null, names: [] };
    entry.names.push(name);
    if (isDefault) {
      // Picking either one silently would bake a coin flip into the snapshot.
      if (entry.default && entry.default !== name) {
        throw new Error(`purl_type ${type} has two defaults: ${entry.default} and ${name}`);
      }
      entry.default = name;
    }
    byType.set(type, entry);
  }

  for (const entry of byType.values()) entry.names.sort();
  return new Map([...byType].sort(([a], [b]) => a.localeCompare(b)));
}

/** Quote keys that are not plain identifiers. */
const key = (value) => (/^[a-z][a-z0-9]*$/i.test(value) ? value : JSON.stringify(value));

function render(byType, registryCount) {
  const withDefault = [...byType].filter(([, entry]) => entry.default);
  const withoutDefault = [...byType].filter(([, entry]) => !entry.default);

  return `${[
    "// Code generated by scripts/sync-registries.mjs. DO NOT EDIT.",
    "//",
    `// Source: GET ${REGISTRIES_URL}`,
    `// Snapshot: ${registryCount} registries, ${byType.size} purl_type values.`,
    "//",
    "// Keys are ecosyste.ms `purl_type` values, not PURL types: there is no `deb` or `apk`",
    "// here, only `debian`, `ubuntu` and `alpine`. See PURL_TYPE_ALIASES in src/purl.ts.",
    "",
    "/** The registry each `purl_type` flags as `default: true`. */",
    "export const DEFAULT_REGISTRY_BY_PURL_TYPE: Readonly<Record<string, string>> = {",
    ...withDefault.map(([type, entry]) => `  ${key(type)}: ${JSON.stringify(entry.default)},`),
    "};",
    "",
    "/**",
    " * `purl_type` values the API serves with no `default: true` registry.",
    " *",
    " * Choosing one is ours: see PINNED_REGISTRIES in src/purl.ts.",
    " */",
    "export const REGISTRIES_WITHOUT_DEFAULT: Readonly<Record<string, readonly string[]>> = {",
    ...withoutDefault.flatMap(([type, entry]) => [
      `  ${key(type)}: [`,
      ...entry.names.map((name) => `    ${JSON.stringify(name)},`),
      "  ],",
    ]),
    "};",
    "",
  ].join("\n")}`;
}

const registries = await fetchRegistries();
const byType = groupByPurlType(registries);
await writeFile(OUT, render(byType, registries.length));

console.log(
  `wrote ${path.relative(ROOT, OUT)}: ${registries.length} registries, ${byType.size} purl types`,
);
